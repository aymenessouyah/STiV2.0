PARTIE_1_CODE = [
    "// ── 1 · Demander le nom (prompt) ──",
    "",
    "function demanderNom() {",
    "  let n = prompt(\"Quel est ton nom ?\");",
    "  if (n !== null && n !== \"\") {",
    "    document.getElementById(\"nom\").value = n;",
    "  }",
    "}",
    "",
    "// ── 2 · Vérifier l'e-mail : un @, un point ──",
    "",
    "function emailValide(mail) {",
    "  let arobase = -1;",
    "  let point = -1;",
    "  for (let i = 0; i < mail.length; i++) {",
    "    if (mail.substr(i, 1) === \"@\" && arobase === -1) {",
    "      arobase = i;",
    "    }",
    "    if (mail.substr(i, 1) === \".\") {",
    "      point = i;",
    "    }",
    "  }",
    "  if (arobase > 0 && point > arobase + 1",
    "      && point < mail.length - 1) {",
    "    return true;",
    "  }",
    "  return false;",
    "}",
    "",
    "// ── 3 · Contrôles de la scène 1 ──",
    "",
    "function identite() {",
    "  let nom = lire(\"nom\");",
    "  if (nom === \"\") {",
    "    alert(\"Le nom est obligatoire !\");",
    "    colorer(\"nom\", false);",
    "    return;",
    "  }",
    "  colorer(\"nom\", true);",
    "  let l = [\"Bonjour \" + nom.substr(0, 1).toUpperCase()",
    "           + nom.substr(1).toLowerCase() + \" !\"];",
    "  if (emailValide(lire(\"email\"))) {",
    "    l.push(\"E-mail valide.\");",
    "    colorer(\"email\", true);",
    "  } else {",
    "    l.push(\"E-mail invalide.\");",
    "    colorer(\"email\", false);",
    "  }",
    "  ecrire(\"res0\", l);",
    "}",
]

