PARTIE_3_CODE = [
    "// ── 6 · Prix du billet ──",
    "",
    "function prix() {",
    "  let t = parseFloat(lire(\"trajet\"));",
    "  let n = parseInt(lire(\"nb\"));",
    "  if (isNaN(t) || isNaN(n) || n < 1) {",
    "    alert(\"Saisis un nombre de billets valide !\");",
    "    return;",
    "  }",
    "  // 1re classe : le tarif est multiplié par 1,5",
    "  let cl = document.getElementsByName(\"classe\");",
    "  for (let i = 0; i < cl.length; i++) {",
    "    if (cl[i].checked && cl[i].value === \"1\") {",
    "      t = t * 1.5;",
    "    }",
    "  }",
    "  // options cochées : on additionne leur prix",
    "  let ob = document.getElementsByName(\"options\");",
    "  let opt = 0;",
    "  for (let i = 0; i < ob.length; i++) {",
    "    if (ob[i].checked) {",
    "      opt = opt + parseFloat(ob[i].value);",
    "    }",
    "  }",
    "  // réduction selon l'âge",
    "  let reduc = 0;",
    "  let nai = lire(\"naissance\");",
    "  if (nai !== \"\") {",
    "    let dn = dateDe(nai);",
    "    let auj = new Date();",
    "    let age = auj.getFullYear() - dn.getFullYear();",
    "    if (auj.getMonth() < dn.getMonth()) { age--; }",
    "    if (age < 12) { reduc = 0.5; }",
    "    else if (age <= 25) { reduc = 0.25; }",
    "  }",
    "  let total = (t * (1 - reduc) + opt) * n;",
    "  if (typeChoisi() === \"retour\") { total = total * 2; }",
    "  let l = [\"Réduction : \" + reduc * 100 + \" %.\",",
    "           \"Options : \" + opt.toFixed(3) + \" DT.\",",
    "           \"Total : \" + total.toFixed(3) + \" DT.\",",
    "           \"Soit \" + Math.round(total * 1000)",
    "           + \" millimes.\"];",
    "  ecrire(\"res2\", l);",
    "}",
]

